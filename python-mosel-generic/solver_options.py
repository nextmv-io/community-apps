"""
Updates the solver options in the app.yaml with the Xpress controls listed in
CONTROLS below. Names and types are checked against the controls of the
installed Xpress version (read from its mmxprs Mosel module). Add controls to
CONTROLS to expose them as options, or use --list to see all available ones.

Usage:
    uv run solver_options.py           # Update the solver options in app.yaml.
    uv run solver_options.py --check   # Fail if the solver options are outdated.
    uv run solver_options.py --list    # List all controls of the installed version.
"""

import ctypes
import glob
import json
import os
import sys
import warnings

MANIFEST = os.path.join(os.path.dirname(os.path.abspath(__file__)), "app.yaml")
BEGIN_MARKER = "      # BEGIN solver options (generated by solver_options.py, do not edit)\n"
END_MARKER = "      # END solver options\n"

# Xpress controls exposed as options, with their descriptions.
CONTROLS = {
    "xprs_maxtime": "Time limit in seconds (negative: stop even if no solution was found yet).",
    "xprs_miprelstop": "Relative MIP gap at which the search stops.",
    "xprs_mipabsstop": "Absolute MIP gap at which the search stops.",
    "xprs_maxmipsol": "Maximum number of MIP solutions to find.",
    "xprs_threads": "Number of threads (-1: determined automatically).",
    "xprs_presolve": "Presolve (0: off, 1: on, 2: on without removing redundant bounds).",
    "xprs_defaultalg": "LP algorithm (1: automatic, 2: dual simplex, 3: primal simplex, 4: barrier).",
    "xprs_cutstrategy": "Cut strategy (-1: automatic, 0: none, 1: conservative, 2: moderate, 3: aggressive).",
    "xprs_heurstrategy": "Heuristic strategy (-1: automatic, 0: none, 1: basic, 2: enhanced, 3: extensive).",
    "xprs_outputlog": "Solver log level (0: off, 1: all messages, 3: errors and warnings, 4: errors).",
}

# Mosel parameter type flags (see XPRMgetnextdsoparam in the Mosel library reference).
TYPES = {1: "int", 2: "float", 3: "string", 4: "bool"}
WRITABLE = 0x2000


def main() -> None:
    """Entry point for the program."""

    available = dict(solver_controls())
    if "--list" in sys.argv[1:]:
        for name, option_type in available.items():
            print(f"{name} ({option_type})")
        return

    controls = []
    for name in CONTROLS:
        if name in available:
            controls.append((name, available[name]))
        else:
            print(f"Control {name} is not available in the installed Xpress version, skipping it.", file=sys.stderr)

    with open(MANIFEST) as f:
        content = f.read()
    start, end = content.find(BEGIN_MARKER), content.find(END_MARKER)
    if start < 0 or end < 0:
        raise ValueError(f"Solver options markers not found in {MANIFEST}.")
    updated = content[: start + len(BEGIN_MARKER)] + options_yaml(controls) + content[end:]

    if "--check" in sys.argv[1:]:
        if updated != content:
            print(
                "Solver options in app.yaml are not in line with the installed Mosel version. "
                "Run `uv run solver_options.py` to update them.",
                file=sys.stderr,
            )
            sys.exit(1)
        print(f"Solver options are up to date ({len(controls)} options).", file=sys.stderr)
        return

    with open(MANIFEST, "w") as f:
        f.write(updated)
    print(f"Updated {len(controls)} solver options in {MANIFEST}.", file=sys.stderr)


def solver_controls() -> list[tuple[str, str]]:
    """Returns the name and type of all writable controls of the mmxprs module."""
    # The license is not needed for reading the controls.
    warnings.filterwarnings("ignore", message="No full Xpress license found")
    import mosellibs
    import moselpy  # noqa: F401 (sets up the Mosel environment)

    lib_path = glob.glob(os.path.join(mosellibs.mosel_libs_dir, "*xprm_rt*"))[0]
    lib = ctypes.CDLL(lib_path)
    lib.XPRMinit()
    lib.XPRMpreloaddso.argtypes = [ctypes.c_char_p]
    lib.XPRMpreloaddso.restype = ctypes.c_void_p
    lib.XPRMpreloaddso(b"mmxprs")
    lib.XPRMfinddso.argtypes = [ctypes.c_char_p]
    lib.XPRMfinddso.restype = ctypes.c_void_p
    dso = lib.XPRMfinddso(b"mmxprs")
    if not dso:
        raise RuntimeError("Mosel module mmxprs not found.")
    lib.XPRMgetnextdsoparam.argtypes = [
        ctypes.c_void_p,
        ctypes.c_void_p,
        ctypes.POINTER(ctypes.c_char_p),
        ctypes.POINTER(ctypes.c_char_p),
        ctypes.POINTER(ctypes.c_int),
    ]
    lib.XPRMgetnextdsoparam.restype = ctypes.c_void_p

    controls = []
    ref = None
    while True:
        name, desc, typ = ctypes.c_char_p(), ctypes.c_char_p(), ctypes.c_int()
        ref = lib.XPRMgetnextdsoparam(dso, ref, ctypes.byref(name), ctypes.byref(desc), ctypes.byref(typ))
        if not ref:
            break
        if typ.value & WRITABLE and typ.value & 0xF in TYPES:
            controls.append((name.value.decode(), TYPES[typ.value & 0xF]))
    return sorted(controls)


def options_yaml(controls: list[tuple[str, str]]) -> str:
    """Returns the manifest options for the given controls."""
    return "".join(
        f"      - name: {name}\n"
        f"        option_type: {option_type}\n"
        f"        description: {json.dumps(f'{CONTROLS[name]} Xpress control {name.upper()}.')}\n"
        "        required: false\n"
        for name, option_type in controls
    )


if __name__ == "__main__":
    main()
